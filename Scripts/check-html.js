const fs = require('node:fs');
const vm = require('node:vm');
const assert = require('node:assert/strict');
const html = fs.readFileSync('art/Clock-Live-Preview.html', 'utf8');
const ids = [...html.matchAll(/\bid="([^"]+)"/g)].map(m => m[1]);
const elements = Object.fromEntries(ids.map(id => [id, {value:'system', textContent:'', attributes:{}, setAttribute(k,v){this.attributes[k]=v;}, showModal(){this.open=true;}, close(){this.open=false;}}]));
elements.tz.options = [...html.matchAll(/<option(?: value="([^"]+)")?>([^<]+)<\/option>/g)].map(m => ({value:m[1] || m[2]}));
let reduced = true;
const sandbox = {console, Intl, Date, performance, document:{getElementById(id){assert.ok(elements[id], `Missing HTML element: ${id}`); return elements[id];}, addEventListener(){}}, localStorage:{getItem(){return null;},setItem(){}}, matchMedia(){return {matches:reduced};}, requestAnimationFrame(fn){fn(performance.now()+200);return 1;}, cancelAnimationFrame(){}, setTimeout(){return 1;}};
vm.createContext(sandbox);
vm.runInContext(html.match(/<script>([\s\S]*?)<\/script>/)[1], sandbox);
assert.match(elements.second.attributes.transform, /rotate\(/);
assert.match(elements.zoneStatus.textContent,/system time zone/);
elements.tz.value='Europe/London';elements.tz.onchange();
assert.match(elements.zoneStatus.textContent,/Europe\/London/);
elements.toggle.onclick();assert.equal(elements.topControl.attributes['aria-pressed'], 'true');
elements.topControl.onkeydown({key:'Enter', preventDefault(){}});assert.equal(elements.topControl.attributes['aria-pressed'], 'false');
elements.aboutOpen.onclick();assert.equal(elements.aboutDialog.open,true);
elements.aboutClose.onclick();assert.equal(elements.aboutDialog.open,false);
const pngs = [...html.matchAll(/data:image\/png;base64,([A-Za-z0-9+/=]+)/g)];
assert.ok(pngs.length >= 2, 'Body and icon must be embedded');
for(const [,b64] of pngs) assert.equal(Buffer.from(b64,'base64').subarray(1,4).toString(),'PNG');
console.log('Passed embedded artwork, timezone, hand transforms, keyboard button and About checks.');
